"""
Writes results/RESULTS_SUMMARY.md: every number needed for the revised manuscript and the
response letter, organised by reviewer comment. Re-run any time; sections whose inputs do not
exist yet are marked PENDING.
"""
from __future__ import annotations

import json

import numpy as np
import pandas as pd

import config as C

R = C.RESULTS_DIR
A = R / "06_analysis"
OUTF = R / "RESULTS_SUMMARY.md"


def _csv(path, **kw):
    p = R / path
    return pd.read_csv(p, **kw) if p.exists() else None


def _json(path):
    p = R / path
    return json.loads(p.read_text(encoding="utf-8")) if p.exists() else None


def f(x, nd=2):
    if x is None or (isinstance(x, float) and np.isnan(x)):
        return "n/a"
    if isinstance(x, (int, np.integer)):
        return f"{x:,}"
    ax = abs(float(x))
    if ax != 0 and ax < 1e-3:
        return f"{x:.1e}"
    return f"{x:.{nd}f}"


def ci(v, nd=2):
    return "[" + ", ".join(f"{float(x):.{nd}f}" for x in v) + "]"


def md_table(df: pd.DataFrame, cols=None, nd=2) -> str:
    if df is None or df.empty:
        return "_PENDING_\n"
    d = df[cols] if cols else df
    head = "| " + " | ".join(map(str, d.columns)) + " |\n|" + "---|" * len(d.columns) + "\n"
    body = "".join("| " + " | ".join(f(v, nd) if isinstance(v, (float, np.floating, int, np.integer)) else str(v)
                                   for v in row) + " |\n" for row in d.itertuples(index=False))
    return head + body


def build() -> str:
    L = ["# Results summary for the revision\n",
         "_Auto-generated by `code/summary.py` from `results/`. Numbers marked PENDING need the human "
         "annotation (notebook 04) or a part not yet run._\n"]

    # ------------------------------------------------------------- data
    L.append("## 1. Data (R1.1, R4.4)\n")
    flow = _csv("01_data/data_flow.csv")
    L.append(md_table(flow))
    notes = _json("01_data/dataset_notes.json")
    if notes:
        L.append(f"\n- Language: {notes['language']}\n- Short reviews: {notes['short_reviews']}\n"
                 f"- {notes['verified_purchase']}\n- Correction for Section 3.1: {notes['paper_section_3_1_correction']}\n")
    cat = _csv("01_data/category_pool_vs_sample.csv")
    if cat is not None:
        L.append("\nCategories (pool vs paper sample):\n\n" + md_table(cat.rename(columns={cat.columns[0]: "category"}), nd=1))
    ext = _csv("01_data/external_data_flow.csv")
    if ext is not None:
        L.append("\nExternal dataset (1429_1, Kindle/Fire/Echo):\n\n" + md_table(ext))

    # ------------------------------------------------------------- reported stats
    L.append("\n## 2. Re-analysis of the statistics printed in the paper (R2.5, R3.4)\n")
    rs = _json("00_reported_stats/reanalysis_from_reported_stats.json")
    ic = _json("00_reported_stats/internal_consistency_check.json")
    if rs:
        L.append(f"- Welch t = {f(rs['welch_t'])}, df = {f(rs['welch_df'],1)}, p = {f(rs['welch_p'],4)}; "
                 f"95% CI of mean difference {ci(rs['welch_ci95_mean_diff'])}\n"
                 f"- Cohen's d = {f(rs['cohens_d'])}, 95% CI {ci(rs['cohens_d_ci95'])}; power of the 16-vs-84 design = "
                 f"{f(rs['power_observed_design_at_d'])}\n")
    if ic:
        L.append(f"- Internal consistency: {ic['verdict']}\n")
    alg = _json("00_reported_stats/rds_formula_algebra.json")
    if alg:
        L.append(f"- RDS formula closed form (R2.4, R3.3): `{alg['closed_form']}`; range {alg['range_of_RDS']}; "
                 f"zero at the scale midpoint.\n")

    # ------------------------------------------------------------- prevalence
    L.append("\n## 3. Regret prevalence by system (R2.1, R3.5, R4.5-4.7)\n")
    L.append("All 2,019 low-rated reviews:\n\n")
    L.append(md_table(_csv("06_analysis/A_prevalence_by_system.csv"),
                      ["system", "description", "n_classified", "n_regret", "pct_regret", "pct_regret_ci95"], nd=1))
    same = _csv("06_analysis/I_systems_on_same_reviews.csv")
    if same is not None:
        p100 = same[same.subset == "paper_sample_100"][["system", "n_regret", "pct_regret", "ci95"]]
        L.append("\nThe paper's original 100 reviews (paper reported 16 regret):\n\n" + md_table(p100, nd=1))
        rnd = same[same.subset == "annotation_random"][["system", "n", "n_regret", "pct_regret", "ci95"]]
        L.append("\nRandom annotation sample (n = 200; includes systems run only on the annotation set):\n\n" + md_table(rnd, nd=1))
    L.append("\nLabel changes caused by each component (same 2,019 reviews; McNemar):\n\n")
    L.append(md_table(_csv("06_analysis/A_label_changes_per_component.csv"),
                      ["change", "pct_changed", "D_to_R", "R_to_D", "mcnemar_p_label_shift"]))

    # ------------------------------------------------------------- decomposition
    L.append("\n## 4. Why the original pipeline gave ~16-22% regret: prompt vs knowledge base\n")
    d2 = _csv("06_analysis/I_decomposition_2x2_annotation_random.csv")
    if d2 is None:
        L.append("_PENDING: run notebook 03b (part 4)._\n")
    else:
        L.append("% regret on the random annotation sample (rows = prompt, columns = knowledge base):\n\n" + md_table(d2, nd=1))
        L.append("\n" + md_table(_csv("06_analysis/I_decomposition_tests.csv"), nd=3))

    # ------------------------------------------------------------- speculative
    L.append("\n## 5. Speculative RAG (R1.2, R3.1, R4.2, R4.7)\n")
    h = _csv("06_analysis/H_speculative_rag_by_subset.csv")
    if h is not None:
        L.append(md_table(h, ["system", "subset", "n_reviews", "draft_regret_rate", "majority_vote_regret_rate",
                              "selected_regret_rate", "pct_selected_differs_from_majority", "pct_unanimous_regret_drafts",
                              "tokens_in_per_review"], nd=3))
        L.append("\nReading: drafts from the small drafter label ~25% of reviews REGRET; the GPT-4o verifier lowers this "
                 "when drafts disagree, but cannot override unanimous drafts, so the selected answer stays above C3.\n")
    hd = _json("06_analysis/H_speculative_rag_diagnostics.json")
    if hd and "tokens_in_per_review_C3" in hd:
        L.append(f"\nCost: Speculative RAG used {f(hd['tokens_in_per_review'],0)} input tokens per review vs "
                 f"{f(hd['tokens_in_per_review_C3'],0)} for C3 (~{f(hd['tokens_in_per_review']/hd['tokens_in_per_review_C3'],1)}x).\n")

    # ------------------------------------------------------------- RDS
    L.append("\n## 6. RDS (R2.4, R2.5, R2.6, R3.2, R3.3, R3.4)\n")
    dd = _json("06_analysis/D_rds_descriptives.json")
    if dd:
        L.append(f"- n = {dd['n_rds']} (errors {dd['n_rds_errors']}); mean {f(dd['rds_mean'])}, SD {f(dd['rds_sd'])}, "
                 f"median {f(dd['rds_median'])}; {f(dd['pct_rds_below_0'],1)}% below 0.\n")
    g = _csv("06_analysis/D_rds_group_comparisons.csv", index_col=0)
    if g is not None:
        keep = ["n_REGRET", "n_DISAPPOINTMENT", "mean_REGRET", "mean_DISAPPOINTMENT", "mean_diff", "welch_t", "welch_df",
                "welch_p", "welch_ci95_low", "welch_ci95_high", "bootstrap_ci95_low", "bootstrap_ci95_high",
                "permutation_p", "mann_whitney_p", "hedges_g", "cohens_d_ci95_low", "cohens_d_ci95_high"]
        gg = g.loc[[k for k in keep if k in g.index]].copy()
        gg.columns = [str(gg.loc[:, c].name) for c in gg.columns]
        hdr = g.loc["grouping"] if "grouping" in g.index else None
        t = gg.apply(pd.to_numeric, errors="coerce")
        if hdr is not None:
            t.columns = list(hdr.values)
        L.append("\nGroup comparison of RDS (note: LLM labels and RDS come from the same model, R3.2):\n\n"
                 + md_table(t.reset_index().rename(columns={"index": "statistic"}), nd=3))
    rc = _csv("06_analysis/D_rating_correlations.csv")
    if rc is not None:
        L.append("\nCorrelation with star rating (ratings restricted to 1-3 by design):\n\n"
                 + md_table(rc, ["subset", "n", "pearson_r", "spearman_rho", "spearman_ci95_boot", "spearman_p"], nd=3))
    ws = _csv("06_analysis/D_weight_sensitivity.csv")
    if ws is not None:
        L.append("\nWeight sensitivity:\n\n" + md_table(ws, nd=3))
    wr = _csv("06_analysis/D_weight_sensitivity_random_draws_summary.csv", index_col=0)
    if wr is not None and "hedges_g_llm_label" in wr.index:
        r_ = wr.loc["hedges_g_llm_label"]
        L.append(f"\n2,000 random weight sets: Hedges' g median {f(r_['50%'])}, 95% of draws in [{f(r_['2.5%'])}, {f(r_['97.5%'])}].\n")

    # ------------------------------------------------------------- others
    L.append("\n## 7. Counterfactual focus (R4.8)\n")
    L.append(md_table(_csv("06_analysis/E_cf_focus_by_LLM_label.csv")))
    L.append("\n" + md_table(_csv("06_analysis/E_cf_focus_tests.csv"), nd=3))
    L.append("\n## 8. Reproducibility (test-retest, random annotation sample)\n")
    st = _csv("06_analysis/C_test_retest_stability.csv")
    L.append(md_table(st, ["run_a", "run_b", "n", "pct_identical", "kappa"] if st is not None else None, nd=3))
    L.append("\n## 9. Generalisability (R2.8, R4.9)\n")
    L.append(md_table(_csv("06_analysis/G_generalisability.csv"), nd=2))
    chi = _json("06_analysis/G_category_chi2.json")
    if chi:
        L.append(f"\nCategory difference: chi2 = {f(chi['chi2'])}, df = {chi['df']}, p = {f(chi['p'],3)}\n")
    L.append("\n## 10. Knowledge base and retrieval\n")
    L.append(md_table(_csv("02_knowledge_base/kb_revised_documents.csv")))
    rsrc = _csv("02_knowledge_base/retrieval_sources_revised.csv")
    if rsrc is not None:
        L.append("\nShare of retrieved chunks by source (C3):\n\n" + md_table(rsrc.rename(columns={rsrc.columns[0]: "source"}), nd=3))

    # ------------------------------------------------------------- human
    L.append("\n## 11. Human annotation (R2.3, R2.7, R3.2, R4.3, R4.6)\n")
    irr = _csv("04_human_annotation/inter_rater_agreement.csv")
    if irr is None:
        L.append("_PENDING: coder sheets not yet returned._\n")
        strata = _csv("04_human_annotation/annotation_strata.csv")
        if strata is not None:
            L.append("\nAnnotation design (random 200 + targeted strata):\n\n" + md_table(strata))
    else:
        L.append("Inter-rater agreement:\n\n" + md_table(irr, nd=3))
        prev = _json("06_analysis/B_human_prevalence.json")
        if prev:
            L.append(f"\nHuman regret prevalence: random sample {f(prev['pct'],1)}% (95% CI {[round(x,1) for x in prev['ci95']]}); "
                     f"stratum-weighted {f(prev['weighted_pct'],1)}% (CI {[round(x,1) for x in prev['weighted_ci95_stratified_bootstrap']]}).\n")
        acc = _csv("06_analysis/B_accuracy_vs_human.csv")
        if acc is not None:
            L.append("\nAccuracy vs human labels:\n\n" + md_table(acc, ["system", "subset", "n", "accuracy", "macro_f1",
                                                                         "kappa_vs_human", "precision_REGRET", "recall_REGRET"], nd=3))
        L.append("\n" + md_table(_csv("06_analysis/B_mcnemar_ablation_tests.csv"), nd=3))
        fr = _csv("06_analysis/F_error_rates_by_feature.csv")
        if fr is not None:
            L.append("\nError analysis:\n\n" + md_table(fr, nd=3))

    # ------------------------------------------------------------- cost
    L.append("\n## 12. API cost\n")
    led = _csv("03_llm_outputs/spend_ledger.csv")
    if led is not None:
        L.append(md_table(led[led.backend == "openai"]) if "backend" in led else md_table(led))
    return "\n".join(L)


def run() -> str:
    txt = build()
    OUTF.write_text(txt, encoding="utf-8")
    print(f"written {OUTF} ({len(txt):,} characters)")
    return str(OUTF)


if __name__ == "__main__":
    run()
